import numpy as np, matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
fig,ax=plt.subplots(figsize=(16,9),dpi=240); fig.patch.set_facecolor("white")
th=np.array([0.5,1.0,1.5,2.0,2.5,3.0])
rc=np.array([0.91,0.88,0.84,0.79,0.72,0.63])
tr=np.linspace(0.5,3.0,100); ci=np.interp(tr,th,rc)
ax.plot(tr,ci,"-",color="#2C5F8D",lw=2.5,label="Rank correlation vs. ε threshold")
ax.scatter(th,rc,s=140,color="#F4B400",edgecolor="black",zorder=5,label="Pilot-2 anchor points")
ax.axhline(0.70,color="#4CAF50",ls="--",lw=2,label="τ_min = 0.70 (frozen threshold)")
ax.axvline(1.95,color="#E53935",ls=":",lw=2,label="ε* ≈ 1.95 (calibrated)")
ax.set_xlabel("ε threshold (tolerance)",fontsize=13)
ax.set_ylabel("Spearman ρ (OPE vs. true ranking)",fontsize=13)
ax.set_title("Figure 9 (illustrative): Pilot-2 Threshold Calibration",fontsize=15,fontweight="bold")
ax.set_xlim(0.4,3.1); ax.set_ylim(0.55,1.0); ax.grid(True,alpha=0.3)
ax.legend(loc="lower left",fontsize=10,framealpha=0.95)
plt.tight_layout(rect=[0,0.04,1,1])
plt.savefig("fig09_pilot2_threshold_calibration.png",dpi=240,bbox_inches="tight",facecolor="white")
plt.close()
print("Saved: fig09_pilot2_threshold_calibration.png")
